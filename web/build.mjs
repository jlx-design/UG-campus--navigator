// Build: esbuild bundles src/ → dist/ (code-split ESM), copies public/, stamps the SW version,
// and renders PWA icons with sharp. Usage: node build.mjs   (UGNAV_* env vars override public config)
import { build } from 'esbuild';
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const root = new URL('.', import.meta.url).pathname;
const dist = join(root, 'dist');
rmSync(dist, { recursive: true, force: true });
mkdirSync(join(dist, 'icons'), { recursive: true });

// White-label: CAMPUS=<id> selects campus/<id>.json (default ug) and generates src/campus.gen.ts.
const campusId = process.env.CAMPUS || 'ug';
const campus = JSON.parse(readFileSync(join(root, `campus/${campusId}.json`), 'utf8'));
writeFileSync(join(root, 'src/campus.gen.ts'), `// GENERATED by build.mjs from campus/${campusId}.json — do not edit.\nexport const CAMPUS = ${JSON.stringify(campus, null, 2)} as const;\n`);
const cfg = {};
for (const k of ['DATA_API_URL', 'AUTH_URL', 'API_URL', 'TILE_URL', 'TILE_ATTRIBUTION']) if (process.env[`UGNAV_${k}`]) cfg[k] = process.env[`UGNAV_${k}`];

const result = await build({
  entryPoints: { app: join(root, 'src/main.tsx') },
  bundle: true, splitting: true, format: 'esm', outdir: dist, minify: true, sourcemap: false, target: ['es2020', 'safari15'],
  jsx: 'automatic', define: { __UGNAV_CONFIG__: JSON.stringify(cfg), 'process.env.NODE_ENV': '"production"' },
  nodePaths: [process.env.NODE_PATH_EXTRA || '/opt/npm-tools/node_modules'],
  entryNames: '[name]', chunkNames: 'chunks/[name]-[hash]', metafile: true, logLevel: 'warning',
});
cpSync(join(root, 'src/styles.css'), join(dist, 'app.css'));
writeFileSync(join(dist, 'index.html'), readFileSync(join(root, 'index.html'), 'utf8').replaceAll('__APP_NAME__', campus.appName).replaceAll('__UNIVERSITY__', campus.university).replaceAll('__THEME__', campus.brand.navy).replaceAll('__PREFS_KEY__', campus.id === 'ug' ? 'ugnav.prefs.v1' : `ugnav.${campus.id}.prefs.v1`));
cpSync(join(root, 'public'), dist, { recursive: true });

const buildId = Date.now().toString(36);
const sw = readFileSync(join(dist, 'sw.js'), 'utf8').replace('__BUILD_ID__', buildId).replaceAll("'ugnav-", campus.id === 'ug' ? "'ugnav-" : `'ugnav-${campus.id}-`).replaceAll('`ugnav-', campus.id === 'ug' ? '`ugnav-' : `\`ugnav-${campus.id}-`);
writeFileSync(join(dist, 'sw.js'), sw);
const mf = JSON.parse(readFileSync(join(dist, 'manifest.webmanifest'), 'utf8'));
Object.assign(mf, { name: `${campus.appName} — ${campus.university}`, short_name: campus.appName, background_color: campus.brand.navy, theme_color: campus.brand.navy,
  description: `Campus map, step-by-step walking directions, timetable, GPA, exams, shuttles, events and an AI campus guide for ${campus.university}.` });
writeFileSync(join(dist, 'manifest.webmanifest'), JSON.stringify(mf, null, 2));

const sharp = require('sharp');
// Icons: a campus logo goes in campus/marks/<id>.svg (512×512, tokens {BG} {FG} {DOT}); until then a plain pin placeholder is used.
// pad=true makes the maskable/Apple version: square, with the mark shrunk into the safe zone.
const markPath = join(root, `campus/marks/${campus.id}.svg`);
const markBody = (existsSync(markPath) ? readFileSync(markPath, 'utf8') : '<g transform="translate(256 262) scale(.92)"><path d="M0-190c-80 0-140 60-140 138C-140 50 0 170 0 170S140 50 140-52c0-78-60-138-140-138Z" fill="{FG}"/><circle cx="0" cy="-52" r="58" fill="{BG}"/><path d="M0-98 18-52 0-6-18-52Z" fill="{DOT}"/></g>')
  .replace(/<!--[\s\S]*?-->/g, '').replaceAll('{BG}', campus.brand.navy).replaceAll('{FG}', campus.brand.gold).replaceAll('{DOT}', '#ffffff');
const logoSvg = (pad, full = false) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><defs><clipPath id="t"><rect width="512" height="512" rx="${pad ? 0 : 112}"/></clipPath></defs>
  <g clip-path="url(#t)"><rect width="512" height="512" fill="${campus.brand.navy}"/><g transform="${pad && !full ? 'translate(56 56) scale(.78125)' : ''}">${markBody}</g></g></svg>`;
const svg = (pad) => Buffer.from(logoSvg(pad));
writeFileSync(join(dist, 'icons/logo.svg'), logoSvg(false));
writeFileSync(join(dist, 'icons/logo-square.svg'), logoSvg(true));
await sharp(svg(false)).resize(1024, 1024).png().toFile(join(dist, 'icons/logo-1024.png'));
await sharp(svg(false)).resize(192, 192).png().toFile(join(dist, 'icons/icon-192.png'));
await sharp(svg(false)).resize(512, 512).png().toFile(join(dist, 'icons/icon-512.png'));
await sharp(svg(true)).resize(512, 512).png().toFile(join(dist, 'icons/icon-maskable-512.png'));
await sharp(Buffer.from(logoSvg(true, true))).resize(180, 180).png().toFile(join(dist, 'icons/apple-touch-icon.png'));

// Hosting config: SPA fallback + security headers (Netlify format).
writeFileSync(join(dist, '.nojekyll'), '');
writeFileSync(join(dist, '_headers'), `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(self), camera=(), microphone=()
  X-Frame-Options: DENY
/sw.js
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
`);

const bytes = Object.entries(result.metafile.outputs).map(([f, o]) => `${f.replace(dist, 'dist')} ${(o.bytes / 1024).toFixed(1)} KB`);
console.log(bytes.join('\n'));
console.log('build', buildId, 'ok', existsSync(join(dist, 'app.js')));
